import AppKit

/// Maps macOS virtual key codes to USB HID keyboard usages, which is what the mouse sends
/// when a button is assigned a keyboard shortcut.
enum KeyCodes {
    private static let table: [(mac: UInt16, usage: UInt8, name: String)] = [
        (0x00, 0x04, "A"), (0x0B, 0x05, "B"), (0x08, 0x06, "C"), (0x02, 0x07, "D"), (0x0E, 0x08, "E"),
        (0x03, 0x09, "F"), (0x05, 0x0A, "G"), (0x04, 0x0B, "H"), (0x22, 0x0C, "I"), (0x26, 0x0D, "J"),
        (0x28, 0x0E, "K"), (0x25, 0x0F, "L"), (0x2E, 0x10, "M"), (0x2D, 0x11, "N"), (0x1F, 0x12, "O"),
        (0x23, 0x13, "P"), (0x0C, 0x14, "Q"), (0x0F, 0x15, "R"), (0x01, 0x16, "S"), (0x11, 0x17, "T"),
        (0x20, 0x18, "U"), (0x09, 0x19, "V"), (0x0D, 0x1A, "W"), (0x07, 0x1B, "X"), (0x10, 0x1C, "Y"),
        (0x06, 0x1D, "Z"),
        (0x12, 0x1E, "1"), (0x13, 0x1F, "2"), (0x14, 0x20, "3"), (0x15, 0x21, "4"), (0x17, 0x22, "5"),
        (0x16, 0x23, "6"), (0x1A, 0x24, "7"), (0x1C, 0x25, "8"), (0x19, 0x26, "9"), (0x1D, 0x27, "0"),
        (0x24, 0x28, "Return"), (0x35, 0x29, "Esc"), (0x33, 0x2A, "Delete"), (0x30, 0x2B, "Tab"),
        (0x31, 0x2C, "Space"), (0x1B, 0x2D, "-"), (0x18, 0x2E, "="), (0x21, 0x2F, "["), (0x1E, 0x30, "]"),
        (0x2A, 0x31, "\\"), (0x29, 0x33, ";"), (0x27, 0x34, "'"), (0x32, 0x35, "`"), (0x2B, 0x36, ","),
        (0x2F, 0x37, "."), (0x2C, 0x38, "/"),
        (0x7A, 0x3A, "F1"), (0x78, 0x3B, "F2"), (0x63, 0x3C, "F3"), (0x76, 0x3D, "F4"), (0x60, 0x3E, "F5"),
        (0x61, 0x3F, "F6"), (0x62, 0x40, "F7"), (0x64, 0x41, "F8"), (0x65, 0x42, "F9"), (0x6D, 0x43, "F10"),
        (0x67, 0x44, "F11"), (0x6F, 0x45, "F12"), (0x69, 0x68, "F13"), (0x6B, 0x69, "F14"), (0x71, 0x6A, "F15"),
        (0x73, 0x4A, "Home"), (0x74, 0x4B, "Page Up"), (0x75, 0x4C, "Forward Delete"), (0x77, 0x4D, "End"),
        (0x79, 0x4E, "Page Down"), (0x7C, 0x4F, "→"), (0x7B, 0x50, "←"), (0x7D, 0x51, "↓"), (0x7E, 0x52, "↑"),
    ]

    static func usage(forMacKeyCode code: UInt16) -> UInt8? {
        table.first { $0.mac == code }?.usage
    }

    /// HID modifier byte: bit 0 Ctrl, 1 Shift, 2 Option, 3 Command (left-hand keys).
    static func modifiers(from flags: NSEvent.ModifierFlags) -> UInt8 {
        var m: UInt8 = 0
        if flags.contains(.control) { m |= 0x01 }
        if flags.contains(.shift) { m |= 0x02 }
        if flags.contains(.option) { m |= 0x04 }
        if flags.contains(.command) { m |= 0x08 }
        return m
    }

    static func shortcutTitle(modifiers m: UInt8, usage: UInt8) -> String {
        var s = ""
        if m & 0x11 != 0 { s += "⌃" }
        if m & 0x44 != 0 { s += "⌥" }
        if m & 0x22 != 0 { s += "⇧" }
        if m & 0x88 != 0 { s += "⌘" }
        return s + (table.first { $0.usage == usage }?.name ?? "Key 0x\(String(usage, radix: 16))")
    }
}
